// Teste de fumaça da interface: percorre a jornada completa e salva screenshots.
// Uso: (servidor rodando em :3001 com base limpa)  node scripts/ui-smoke.mjs ./screenshots
// Requer playwright-core (dependência da API) e Chromium disponível.
import { createRequire } from 'node:module';
const { chromium } = createRequire(new URL('../apps/api/package.json', import.meta.url))('playwright-core');
const OUT = process.argv[2];
const B = 'http://localhost:3001';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1500, height: 920 } });
const errors = [];
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
page.on('pageerror', (e) => errors.push(String(e)));
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` });
async function loginAs(name) {
  await page.evaluate(() => localStorage.clear());
  await page.goto(`${B}/entrar`);
  await page.getByText(name, { exact: true }).click();
  await page.waitForURL(`${B}/`);
}
